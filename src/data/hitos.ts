export function getCategories(): string[] {
  const categoriesSet = new Set<string>();
  HITOS_DATASET.forEach(item => categoriesSet.add(item.categoria));
  return ["Todas las Eras", ...Array.from(categoriesSet).sort()];
}

export function getRandomHito(categoryFilter?: string): HitoHistorico {
  let pool = HITOS_DATASET;
  if (categoryFilter && categoryFilter !== "Todas las Eras") {
    const filtered = HITOS_DATASET.filter(item => item.categoria === categoryFilter);
    if (filtered.length > 0) pool = filtered;
  }
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
